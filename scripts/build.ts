/**
 * Compiles tokens/fox.tokens.json (DTCG 2025.10) into the files the library
 * ships: CSS custom properties, a typed TS module, a Tailwind v4 @theme layer
 * and a flat JSON map. Deterministic: the same token file always produces
 * byte-identical output, which tests/build.test.ts relies on.
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";

const ROOT = join(import.meta.dir, "..");
const TOKEN_FILE = join(ROOT, "tokens", "fox.tokens.json");
const DIST = join(ROOT, "dist");

export type TokenValue = string | number | readonly (string | number)[];
export interface Leaf {
  path: string[];
  type: string;
  value: TokenValue;
  description?: string;
}

/** Groups that are selector overrides rather than :root variables. */
const SELECTOR_GROUPS: Record<
  string,
  { selector: string; label: string; rename?: string }
> = {
  "color-light": {
    selector: '[data-theme="light"]',
    label: "Light theme",
    rename: "color",
  },
  "density-compact": {
    selector: '[data-density="compact"]',
    label: "Compact density",
  },
};

/** DTCG group prefix -> Tailwind v4 theme namespace. */
const TAILWIND_NAMESPACE: Record<string, string> = {
  color: "color",
  space: "spacing",
  radius: "radius",
  font: "font",
  text: "text",
  leading: "leading",
  weight: "font-weight",
  shadow: "shadow",
  ease: "ease",
};

type Json = Record<string, unknown>;

export function flatten(
  node: Json,
  path: string[] = [],
  inherited?: string,
): Leaf[] {
  const out: Leaf[] = [];
  const groupType = typeof node.$type === "string" ? node.$type : inherited;
  for (const [key, raw] of Object.entries(node)) {
    if (key.startsWith("$")) continue;
    if (raw === null || typeof raw !== "object" || Array.isArray(raw)) {
      throw new Error(`token ${[...path, key].join(".")} is not an object`);
    }
    const child = raw as Json;
    if (child.$value !== undefined) {
      const type = typeof child.$type === "string" ? child.$type : groupType;
      if (!type)
        throw new Error(`token ${[...path, key].join(".")} has no $type`);
      out.push({
        path: [...path, key],
        type,
        value: child.$value as TokenValue,
        description:
          typeof child.$description === "string"
            ? child.$description
            : undefined,
      });
    } else {
      out.push(...flatten(child, [...path, key], groupType));
    }
  }
  return out;
}

/** CSS text for a token value; arrays are font stacks or cubic-bezier points. */
export function cssValue(leaf: Leaf): string {
  if (Array.isArray(leaf.value)) {
    if (leaf.value.every((v) => typeof v === "number")) {
      return `cubic-bezier(${leaf.value.join(", ")})`;
    }
    return leaf.value
      .map((v) => (String(v).includes(" ") ? `"${v}"` : String(v)))
      .join(", ");
  }
  return String(leaf.value);
}

export function varName(path: string[]): string {
  return `--fox-${path.join("-")}`;
}

function groupByTop(leaves: Leaf[]): Map<string, Leaf[]> {
  const groups = new Map<string, Leaf[]>();
  for (const leaf of leaves) {
    const top = leaf.path[0] ?? "";
    groups.set(top, [...(groups.get(top) ?? []), leaf]);
  }
  return groups;
}

function block(selector: string, leaves: Leaf[]): string {
  const lines: string[] = [`${selector} {`];
  let first = true;
  for (const [top, group] of groupByTop(leaves)) {
    if (!first) lines.push("");
    first = false;
    lines.push(`  /* ${top} */`);
    for (const leaf of group) {
      lines.push(`  ${varName(leaf.path)}: ${cssValue(leaf)};`);
    }
  }
  lines.push("}");
  return lines.join("\n");
}

/** Override groups reuse the dark variable names: color-light -> color, density-compact -> bare. */
function overridePath(group: string, path: string[]): string[] {
  const rename = SELECTOR_GROUPS[group]?.rename;
  return rename ? [rename, ...path.slice(1)] : path.slice(1);
}

export function buildCss(leaves: Leaf[]): string {
  const root = leaves.filter((l) => !SELECTOR_GROUPS[l.path[0] ?? ""]);
  const parts = [
    "/* Generated by scripts/build.ts from tokens/fox.tokens.json (DTCG 2025.10).",
    "   Do not edit: change the token file and run `bun run build`. */",
    "",
    block(":root", root),
  ];
  for (const [group, { selector, label }] of Object.entries(SELECTOR_GROUPS)) {
    const overrides = leaves
      .filter((l) => l.path[0] === group)
      .map((leaf) => ({ ...leaf, path: overridePath(group, leaf.path) }));
    if (overrides.length === 0) continue;
    parts.push("", `/* ${label} */`, block(selector, overrides));
  }
  return `${parts.join("\n")}\n`;
}

function toObject(leaves: Leaf[]): Json {
  const root: Json = {};
  for (const leaf of leaves) {
    let cursor = root;
    const keys = leaf.path.slice(0, -1);
    for (const key of keys) {
      const next = cursor[key];
      if (next === undefined) {
        const created: Json = {};
        cursor[key] = created;
        cursor = created;
      } else {
        cursor = next as Json;
      }
    }
    cursor[leaf.path[leaf.path.length - 1] as string] = leaf.value;
  }
  return root;
}

export function buildTs(leaves: Leaf[]): string {
  const main = leaves.filter((l) => !SELECTOR_GROUPS[l.path[0] ?? ""]);
  // In TS the override objects mirror `tokens.color` / `tokens.space`: no group prefix.
  const light = leaves
    .filter((l) => l.path[0] === "color-light")
    .map((l) => ({ ...l, path: l.path.slice(1) }));
  const compact = leaves
    .filter((l) => l.path[0] === "density-compact")
    .map((l) => ({ ...l, path: l.path.slice(1) }));
  const names = main.map((l) => l.path.join(".")).sort();
  const colorNames = main
    .filter((l) => l.path[0] === "color")
    .map((l) => l.path.join("."));
  const json = (value: Json) => JSON.stringify(value, null, 2);

  return `/* Generated by scripts/build.ts from tokens/fox.tokens.json. Do not edit. */

export const tokens = ${json(toObject(main))} as const;

/** Same names as \`tokens.color\`, values of the [data-theme="light"] override. */
export const lightColor = ${json(toObject(light))} as const;

/** Same names as \`tokens.space\` / \`tokens.text\`, values of the compact density. */
export const compactDensity = ${json(toObject(compact))} as const;

export type Tokens = typeof tokens;
export type ColorToken = ${colorNames.length ? colorNames.map((n) => JSON.stringify(n)).join(" | ") : "never"};
export type TokenName =
${names.map((n) => `  | ${JSON.stringify(n)}`).join("\n")};

/** The CSS custom property for a token path, e.g. color.bg.deep -> --fox-color-bg-deep. */
export function cssVar(path: TokenName): string {
  return \`--fox-\${path.replaceAll(".", "-")}\`;
}

export function tokenValue(path: TokenName): string | number {
  const parts = path.split(".");
  let cursor: unknown = tokens;
  for (const part of parts) {
    cursor = (cursor as Record<string, unknown>)[part];
  }
  if (cursor === undefined) throw new Error(\`unknown token: \${path}\`);
  return cursor as string | number;
}
`;
}

export function buildTailwind(leaves: Leaf[]): string {
  const main = leaves.filter((l) => !SELECTOR_GROUPS[l.path[0] ?? ""]);
  const lines = [
    "/* Generated by scripts/build.ts. Optional Tailwind v4 layer for projects that",
    "   want the fox tokens as utilities; the design system itself needs no Tailwind. */",
    "@theme {",
  ];
  for (const leaf of main) {
    const namespace = TAILWIND_NAMESPACE[leaf.path[0] ?? ""];
    if (!namespace) continue;
    const rest = leaf.path.slice(1).join("-");
    const name = rest ? `--${namespace}-fox-${rest}` : `--${namespace}-fox`;
    lines.push(`  ${name}: ${cssValue(leaf)};`);
  }
  lines.push("}");
  return `${lines.join("\n")}\n`;
}

function write(file: string, content: string): "wrote" | "unchanged" {
  let previous = "";
  try {
    previous = readFileSync(file, "utf8");
  } catch {
    previous = "";
  }
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, content);
  return previous === content ? "unchanged" : "wrote";
}

export function build(): void {
  const source = JSON.parse(readFileSync(TOKEN_FILE, "utf8")) as Json;
  const leaves = flatten(source);

  const seen = new Set<string>();
  for (const leaf of leaves) {
    const name = varName(leaf.path);
    if (seen.has(name)) throw new Error(`duplicate token variable: ${name}`);
    seen.add(name);
  }

  const css = buildCss(leaves);
  const base = readFileSync(join(ROOT, "src", "base.css"), "utf8");
  const components = readFileSync(join(ROOT, "src", "components.css"), "utf8");
  const index = [
    "/* @schlaufuchs/design-system: tokens + base + components in one file. */",
    css,
    base,
    components,
  ].join("\n");

  const flat: Json = {};
  for (const leaf of leaves) {
    flat[leaf.path.join(".")] = { value: leaf.value, type: leaf.type };
  }

  const results = {
    "dist/tokens.css": write(join(DIST, "tokens.css"), css),
    "dist/tokens.ts": write(join(DIST, "tokens.ts"), buildTs(leaves)),
    "dist/theme.tailwind.css": write(
      join(DIST, "theme.tailwind.css"),
      buildTailwind(leaves),
    ),
    "dist/tokens.json": write(
      join(DIST, "tokens.json"),
      `${JSON.stringify(flat, null, 2)}\n`,
    ),
    "dist/index.css": write(join(DIST, "index.css"), index),
  };
  copyFileSync(
    join(DIST, "index.css"),
    join(ROOT, "docs", "design-system.css"),
  );
  console.log(`${leaves.length} tokens`);
  for (const [file, state] of Object.entries(results))
    console.log(`${state.padEnd(9)} ${file}`);
}

if (import.meta.main) build();
